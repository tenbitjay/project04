create or replace function public.is_sudoku_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1 from public.sudoku_admins
        where user_id = auth.uid()
    );
$$;

create or replace function public.set_my_nickname(p_nickname text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_nickname text := btrim(p_nickname);
begin
    if v_user_id is null then
        raise exception 'Join the game before choosing a nickname.';
    end if;
    if v_nickname !~ '^[A-Za-z0-9][A-Za-z0-9_-]{2,19}$' then
        raise exception 'Use 3–20 letters, numbers, underscores, or hyphens; start with a letter or number.';
    end if;

    insert into public.profiles (id, nickname)
    values (v_user_id, v_nickname)
    on conflict (id) do update set nickname = excluded.nickname;

    return v_nickname;
end;
$$;

drop function if exists public.get_leaderboard();
create function public.get_leaderboard()
returns table (
    nickname text,
    total_points bigint,
    solved_levels integer,
    best_points integer,
    best_difficulty text,
    best_time_limit_seconds integer,
    best_elapsed_seconds integer
)
language sql
stable
security definer
set search_path = ''
as $$
    with totals as (
        select s.user_id, sum(s.points)::bigint as total_points, count(*)::integer as solved_levels
        from public.scores as s
        group by s.user_id
    )
    select p.nickname, totals.total_points, totals.solved_levels,
           best.points, best.difficulty, best.time_limit_seconds, best.elapsed_seconds
    from totals
    join public.profiles as p on p.id = totals.user_id
    join lateral (
        select s.points, s.difficulty, s.time_limit_seconds, s.elapsed_seconds
        from public.scores as s
        where s.user_id = totals.user_id
        order by s.points desc, s.elapsed_seconds asc
        limit 1
    ) as best on true
    order by totals.total_points desc, best.elapsed_seconds asc, p.nickname asc
    limit 10;
$$;

drop function if exists public.record_sudoku_score(text, integer);
create or replace function public.record_sudoku_score(
    p_difficulty text,
    p_elapsed_seconds integer,
    p_time_limit_seconds integer
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_base_points integer;
    v_points integer;
begin
    if v_user_id is null then
        raise exception 'Join the game before saving a score.';
    end if;
    if p_difficulty not in ('easy', 'medium', 'hard') then
        raise exception 'Choose a valid difficulty.';
    end if;
    if p_elapsed_seconds < 1 then
        raise exception 'A game time must be at least 1 second.';
    end if;
    if p_time_limit_seconds not in (0, 300, 600, 900) then
        raise exception 'Choose a valid game time limit.';
    end if;
    if p_time_limit_seconds > 0 and p_elapsed_seconds > p_time_limit_seconds then
        raise exception 'The game was completed after its time limit.';
    end if;
    if not exists (select 1 from public.profiles where id = v_user_id) then
        raise exception 'Choose a nickname before saving a score.';
    end if;

    v_base_points := case p_difficulty
        when 'easy' then 1000
        when 'medium' then 2000
        else 3000
    end;
    v_points := v_base_points + greatest(0, 600 - floor(p_elapsed_seconds * 2.0 / 3)::integer);

    insert into public.scores (
        user_id, difficulty, points, elapsed_seconds, time_limit_seconds, updated_at
    )
    values (
        v_user_id, p_difficulty, v_points, p_elapsed_seconds, p_time_limit_seconds, now()
    )
    on conflict (user_id, difficulty) do update
        set points = excluded.points,
            elapsed_seconds = excluded.elapsed_seconds,
            time_limit_seconds = excluded.time_limit_seconds,
            updated_at = now()
        where excluded.points > public.scores.points;

    return v_points;
end;
$$;

create or replace function public.send_chat_message(p_body text)
returns table (id bigint, nickname text, body text, created_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_nickname text;
    v_body text := btrim(p_body);
    v_id bigint;
    v_created_at timestamptz;
begin
    if v_user_id is null then
        raise exception 'Join the game before sending a message.';
    end if;
    if char_length(v_body) not between 1 and 280 then
        raise exception 'Messages must contain 1–280 characters.';
    end if;

    select p.nickname into v_nickname
    from public.profiles as p
    where p.id = v_user_id;
    if v_nickname is null then
        raise exception 'Choose a nickname before sending a message.';
    end if;
    if exists (
        select 1 from public.chat_messages as c
        where c.user_id = v_user_id
          and c.created_at > now() - interval '3 seconds'
    ) then
        raise exception 'Please wait a few seconds before sending another message.';
    end if;
    if (
        select count(*) from public.chat_messages as c
        where c.user_id = v_user_id
          and c.created_at > now() - interval '1 minute'
    ) >= 10 then
        raise exception 'You have sent too many messages. Try again in a minute.';
    end if;

    delete from public.chat_messages as old_message
    where old_message.created_at < now() - interval '30 days';

    insert into public.chat_messages (user_id, nickname, body)
    values (v_user_id, v_nickname, v_body)
    returning chat_messages.id, chat_messages.created_at
    into v_id, v_created_at;

    return query select v_id, v_nickname, v_body, v_created_at;
end;
$$;

