create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    nickname text not null check (char_length(nickname) between 2 and 20),
    created_at timestamptz not null default now()
);

create unique index if not exists profiles_nickname_lower_unique
    on public.profiles (lower(nickname));

create table if not exists public.sudoku_admins (
    user_id uuid primary key references auth.users (id) on delete cascade
);

create table if not exists public.scores (
    user_id uuid not null references auth.users (id) on delete cascade,
    difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
    points integer not null check (points > 0),
    elapsed_seconds integer not null,
    time_limit_seconds integer not null default 0,
    updated_at timestamptz not null default now(),
    primary key (user_id, difficulty)
);

alter table public.scores
    add column if not exists time_limit_seconds integer not null default 0;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.scores'::regclass
          and conname = 'scores_time_limit_seconds_check'
    ) then
        alter table public.scores
            add constraint scores_time_limit_seconds_check
            check (time_limit_seconds in (0, 300, 600, 900));
    end if;
end;
$$;

alter table public.scores drop constraint if exists scores_elapsed_seconds_check;
alter table public.scores
    add constraint scores_elapsed_seconds_check
    check (elapsed_seconds >= 1);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    nickname text not null,
    body text not null check (char_length(body) between 1 and 280),
    created_at timestamptz not null default now()
);

create index if not exists chat_messages_created_at_idx
    on public.chat_messages (created_at desc);
create index if not exists chat_messages_user_created_at_idx
    on public.chat_messages (user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.sudoku_admins enable row level security;
alter table public.scores enable row level security;
alter table public.chat_messages enable row level security;

