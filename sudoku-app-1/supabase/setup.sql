create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    nickname text not null check (char_length(nickname) between 2 and 20),
    created_at timestamptz not null default now()
);

create unique index if not exists profiles_nickname_lower_unique
    on public.profiles (lower(nickname));

create table if not exists public.scores (
    user_id uuid not null references auth.users (id) on delete cascade,
    difficulty text not null check (difficulty in ('easy', 'medium', 'hard')),
    points integer not null check (points > 0),
    elapsed_seconds integer not null check (elapsed_seconds between 15 and 7200),
    updated_at timestamptz not null default now(),
    primary key (user_id, difficulty)
);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    nickname text not null,
    body text not null check (char_length(body) between 1 and 280),
    created_at timestamptz not null default now()
);

create index if not exists chat_messages_created_at_idx
    on public.chat_messages (created_at desc);
create index if not exists chat_messages_user_created_at_idx
    on public.chat_messages (user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.scores enable row level security;
alter table public.chat_messages enable row level security;

drop policy if exists "Public can read profiles" on public.profiles;
create policy "Public can read profiles"
    on public.profiles for select to anon, authenticated using (true);

drop policy if exists "Public can read scores" on public.scores;
create policy "Public can read scores"
    on public.scores for select to anon, authenticated using (true);

drop policy if exists "Public can read chat" on public.chat_messages;
create policy "Public can read chat"
    on public.chat_messages for select to anon, authenticated using (true);

revoke all on public.profiles, public.scores, public.chat_messages from public, anon, authenticated;
grant select on public.profiles, public.scores, public.chat_messages to anon, authenticated;

create or replace function public.set_my_nickname(p_nickname text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_nickname text := btrim(p_nickname);
begin
    if v_user_id is null then
        raise exception 'Join the game before choosing a nickname.';
    end if;
    if v_nickname !~ '^[A-Za-z0-9][A-Za-z0-9 _-]{1,19}$' then
        raise exception 'Use 2–20 letters, numbers, spaces, underscores, or hyphens; start with a letter or number.';
    end if;

    insert into public.profiles (id, nickname)
    values (v_user_id, v_nickname)
    on conflict (id) do update set nickname = excluded.nickname;

    return v_nickname;
end;
$$;

create or replace function public.get_leaderboard()
returns table (nickname text, total_points bigint, solved_levels integer)
language sql
stable
security definer
set search_path = ''
as $$
    select p.nickname, sum(s.points)::bigint, count(*)::integer
    from public.scores as s
    join public.profiles as p on p.id = s.user_id
    group by p.id, p.nickname
    order by sum(s.points) desc, min(s.elapsed_seconds) asc, p.nickname asc
    limit 10;
$$;

create or replace function public.record_sudoku_score(
    p_difficulty text,
    p_elapsed_seconds integer
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_base_points integer;
    v_points integer;
begin
    if v_user_id is null then
        raise exception 'Join the game before saving a score.';
    end if;
    if p_difficulty not in ('easy', 'medium', 'hard') then
        raise exception 'Choose a valid difficulty.';
    end if;
    if p_elapsed_seconds not between 15 and 7200 then
        raise exception 'A game time must be between 15 seconds and 2 hours.';
    end if;
    if not exists (select 1 from public.profiles where id = v_user_id) then
        raise exception 'Choose a nickname before saving a score.';
    end if;

    v_base_points := case p_difficulty
        when 'easy' then 1000
        when 'medium' then 2000
        else 3000
    end;
    v_points := v_base_points + greatest(0, 600 - p_elapsed_seconds);

    insert into public.scores (user_id, difficulty, points, elapsed_seconds, updated_at)
    values (v_user_id, p_difficulty, v_points, p_elapsed_seconds, now())
    on conflict (user_id, difficulty) do update
        set points = excluded.points,
            elapsed_seconds = excluded.elapsed_seconds,
            updated_at = now()
        where excluded.points > public.scores.points;

    return v_points;
end;
$$;

create or replace function public.send_chat_message(p_body text)
returns table (id bigint, nickname text, body text, created_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_nickname text;
    v_body text := btrim(p_body);
    v_id bigint;
    v_created_at timestamptz;
begin
    if v_user_id is null then
        raise exception 'Join the game before sending a message.';
    end if;
    if char_length(v_body) not between 1 and 280 then
        raise exception 'Messages must contain 1–280 characters.';
    end if;

    select p.nickname into v_nickname
    from public.profiles as p
    where p.id = v_user_id;
    if v_nickname is null then
        raise exception 'Choose a nickname before sending a message.';
    end if;
    if exists (
        select 1 from public.chat_messages as c
        where c.user_id = v_user_id
          and c.created_at > now() - interval '3 seconds'
    ) then
        raise exception 'Please wait a few seconds before sending another message.';
    end if;
    if (
        select count(*) from public.chat_messages as c
        where c.user_id = v_user_id
          and c.created_at > now() - interval '1 minute'
    ) >= 10 then
        raise exception 'You have sent too many messages. Try again in a minute.';
    end if;

    delete from public.chat_messages as old_message
    where old_message.created_at < now() - interval '30 days';

    insert into public.chat_messages (user_id, nickname, body)
    values (v_user_id, v_nickname, v_body)
    returning chat_messages.id, chat_messages.created_at
    into v_id, v_created_at;

    return query select v_id, v_nickname, v_body, v_created_at;
end;
$$;

